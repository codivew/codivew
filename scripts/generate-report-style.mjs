import { readFile, unlink, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format } from 'prettier';

const compiledCssPath = resolve('.report-style.tmp.css');
const generatedModulePath = resolve('src/reporting/report-style.generated.ts');

try {
  const css = await readFile(compiledCssPath, 'utf8');
  const module = await format(
    `// Generated by scripts/generate-report-style.mjs. Do not edit.\nexport const REPORT_STYLE: string = ${JSON.stringify(css)};\n`,
    { parser: 'typescript' },
  );
  await writeFile(generatedModulePath, module, 'utf8');
} finally {
  await unlink(compiledCssPath).catch((error) => {
    if (error.code !== 'ENOENT') throw error;
  });
}
